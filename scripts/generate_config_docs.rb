#!/usr/bin/env ruby
# frozen_string_literal: true

require "json"

ROOT_DIR = File.expand_path("..", __dir__)
SCHEMA_PATH = File.join(ROOT_DIR, "docs", "config-schema.json")
OUTPUT_PATH = File.join(ROOT_DIR, "docs", "configuration.md")

def resolve_pointer(document, pointer)
  return document if pointer == "#"

  tokens = pointer.sub(%r{\A#/}, "").split("/").map do |token|
    token.gsub("~1", "/").gsub("~0", "~")
  end

  tokens.reduce(document) do |memo, token|
    memo.fetch(token)
  end
end

def dereference(node, schema)
  return node unless node.is_a?(Hash) && node["$ref"]

  referenced = resolve_pointer(schema, node["$ref"])
  referenced.merge(node.except("$ref"))
end

def format_default(value)
  case value
  when String
    value
  when Numeric, TrueClass, FalseClass
    value.to_s
  else
    JSON.generate(value)
  end
end

def schema_type(node)
  return ref_name(node["$ref"]) if node["$ref"]

  type = node["type"]
  return "any" unless type

  if type.is_a?(Array)
    return type.join(" | ")
  end

  if type == "array"
    item = node["items"] || {}
    return "array<#{schema_type(item)}>"
  end

  if type == "object"
    additional = node["additionalProperties"]
    if additional.is_a?(Hash) && additional["$ref"] && !node["properties"]&.any?
      return "object<string, #{ref_name(additional["$ref"])}>"
    end
  end

  type
end

def ref_name(ref)
  ref.split("/").last
end

def normalized_description(node, schema)
  effective = dereference(node, schema)
  parts = []
  parts << effective["description"] if effective["description"]

  if effective["enum"]
    enum_values = effective["enum"].map { |value| "`#{format_default(value)}`" }
    parts << "Allowed values: #{enum_values.join(", ")}."
  end

  if effective.key?("minimum")
    parts << "Minimum: `#{effective["minimum"]}`."
  end

  if effective.key?("maximum")
    parts << "Maximum: `#{effective["maximum"]}`."
  end

  parts.join(" ")
end

def render_rows(node, schema)
  required = Array(node["required"])

  (node["properties"] || {}).map do |name, property_schema|
    effective = dereference(property_schema, schema)
    cli_flags = Array(property_schema["x-cli-flags"]).map { |flag| "`#{flag}`" }

    {
      name: name,
      type: schema_type(property_schema),
      required: required.include?(name) ? "yes" : "no",
      default: effective.key?("default") ? "`#{format_default(effective["default"])}`" : "-",
      cli: cli_flags.empty? ? "-" : cli_flags.join(", "),
      description: normalized_description(property_schema, schema)
    }
  end
end

def escape_cell(value)
  value.to_s.gsub("|", "\\|")
end

def additional_properties_note(node)
  additional = node["additionalProperties"]
  return nil unless node["type"] == "object" || node["properties"]

  case additional
  when true
    "Additional properties are allowed."
  when false
    "Additional properties are not allowed."
  when Hash
    if additional["$ref"]
      "Additional properties must match `#{ref_name(additional["$ref"])}`."
    else
      "Additional properties must match `#{schema_type(additional)}`."
    end
  end
end

def collect_cli_flags(node, schema, path = [], output = [])
  return output unless node.is_a?(Hash)

  if node["x-cli-flags"]
    output << {
      path: path.join("."),
      flags: node["x-cli-flags"],
      type: schema_type(node),
      description: normalized_description(node, schema)
    }
  end

  (node["properties"] || {}).each do |name, child|
    collect_cli_flags(child, schema, path + [name], output)
  end

  output
end

schema = JSON.parse(File.read(SCHEMA_PATH))

lines = []
lines << "<!-- Generated by scripts/generate_config_docs.rb from docs/config-schema.json. Do not edit directly. -->"
lines << ""
lines << "# Configuration Reference"
lines << ""
lines << "Canonical source: `docs/config-schema.json`."
lines << ""
lines << "Nerve computes effective runtime configuration from layered sources."
lines << ""
lines << "## Configuration Inputs"
lines << ""

Array(schema["x-config-sources"]).each do |source|
  required = source["required"] ? "required" : "optional"
  flag = source["flag"] ? " (`#{source["flag"]}`)" : ""
  lines << "- `#{source["name"]}`#{flag}: #{required}. #{source["description"]}"
end

lines << ""
lines << "## Configuration Precedence"
lines << ""
lines << "Highest precedence first:"
lines << ""
Array(schema["x-config-precedence"]).each_with_index do |source, index|
  lines << "#{index + 1}. #{source["source"]}: #{source["description"]}"
end

lines << ""
lines << "## Load And Merge Order"
lines << ""
Array(schema["x-load-order"]).each_with_index do |step, index|
  lines << "#{index + 1}. #{step}"
end

cli_flags = collect_cli_flags(schema, schema)

lines << ""
lines << "## CLI Override Flags"
lines << ""
lines << "Only selected global fields are CLI-overridable today:"
lines << ""
lines << "| Config path | CLI flags | Type | Notes |"
lines << "| --- | --- | --- | --- |"
cli_flags.each do |entry|
  flags = entry[:flags].map { |flag| "`#{flag}`" }.join(", ")
  lines << "| `#{entry[:path]}` | #{flags} | `#{entry[:type]}` | #{escape_cell(entry[:description])} |"
end

Array(schema["x-doc-sections"]).each do |section|
  node = resolve_pointer(schema, section["pointer"])
  lines << ""
  lines << "## #{section["title"]}"
  lines << ""
  lines << node["description"] if node["description"]
  lines << "" if node["description"]

  rows = render_rows(node, schema)
  if rows.empty?
    lines << "No fields documented in this section."
  else
    lines << "| Field | Type | Required | Default | CLI flags | Description |"
    lines << "| --- | --- | --- | --- | --- | --- |"
    rows.each do |row|
      description = row[:description].empty? ? "-" : escape_cell(row[:description])
      lines << "| `#{row[:name]}` | `#{row[:type]}` | #{row[:required]} | #{row[:default]} | #{row[:cli]} | #{description} |"
    end
  end

  note = additional_properties_note(node)
  if note
    lines << ""
    lines << note
  end
end

lines << ""
lines << "## Extensibility"
lines << ""
lines << "- Top-level config allows additional properties so operators can carry non-core config values."
lines << "- Service objects allow additional properties for custom reporters and service-specific extensions."
lines << "- Check objects allow additional properties for plugin-defined check parameters."

examples = Array(schema["x-cli-examples"])
unless examples.empty?
  lines << ""
  lines << "## Examples"

  examples.each do |example_lines|
    lines << ""
    lines << "```bash"
    example_lines.each { |line| lines << line }
    lines << "```"
  end
end

File.write(OUTPUT_PATH, lines.join("\n") + "\n")
puts "Wrote #{OUTPUT_PATH}"
